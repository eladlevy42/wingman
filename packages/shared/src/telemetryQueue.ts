import {
  MAX_TELEMETRY_BATCH,
  type TelemetryBatch,
  type TelemetryScreen,
} from "./schemas/telemetry";
import type { AuditEventPayload, ClientAuditEventType } from "./schemas/audit";

// The client-side half of telemetry (docs/adr/0038, #554), with no React and no
// platform API in it: both clients must queue, batch, cap and drop identically
// for a funnel comparison between them to mean anything, and two copies of
// "when do we drop?" is a correctness risk rather than a convenience
// (CLAUDE.md §3). The transport and the timer are injected — those are the
// parts that genuinely differ (fetch + AppState on mobile, fetch +
// visibilitychange on web).

// One queued event, before it is addressed to a subject. The subject is
// resolved at flush time, not at track time, so an event queued while signed
// out is still sent under the anonymous id it was emitted under.
export interface QueuedTelemetryEvent {
  type: ClientAuditEventType;
  payload: unknown;
  // The subject this event was emitted under, captured at track() time.
  userId: string | null;
  anonSessionId: string;
}

export interface TelemetryQueueOptions {
  // The anonymous, per-launch session id (docs/adr/0038). Generated by the
  // client and held in memory only — never persisted, never stitched to a
  // userId, which is why it is passed in rather than derived from storage.
  anonSessionId: string;
  // Sends one batch. Resolves on success, rejects on any failure — the queue
  // treats a rejection as "these events are gone" (see flush).
  send: (batch: TelemetryBatch) => Promise<void>;
  // Events held before the oldest is dropped. A phone on the wrong LAN is the
  // most common failure in this app, and an unbounded queue on a client that
  // cannot reach the API is a memory leak that outlives the outage.
  maxQueued?: number;
}

export const DEFAULT_MAX_QUEUED = 200;

export interface TelemetryQueue {
  track<T extends ClientAuditEventType>(type: T, payload: AuditEventPayload<T>): void;
  // Sends everything queued, in batches of at most MAX_TELEMETRY_BATCH.
  // Never rejects: telemetry is subordinate to the app using it.
  flush(): Promise<void>;
  // Binds subsequent events to a signed-in user. Passing null returns to the
  // anonymous id — a sign-out, not a link back to anything.
  //
  // Events already queued keep the subject they were emitted under, so
  // registering does NOT backfill a userId onto the pre-auth events that led
  // to it. That non-linkage is the whole point of the anonymous id.
  setUser(userId: string | null): void;
  // Queue depth, for tests and a dev console.
  size(): number;
}

// Splits a list into chunks the endpoint will accept.
export function chunk<T>(items: T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size));
  return out;
}

// Groups queued events by the subject they were emitted under. A single flush
// can span a sign-in, and a batch carries exactly one subject.
export function groupBySubject(events: QueuedTelemetryEvent[]): TelemetryBatch[] {
  const bySubject = new Map<string, QueuedTelemetryEvent[]>();
  for (const event of events) {
    const key = event.userId ?? `anon:${event.anonSessionId}`;
    const group = bySubject.get(key);
    if (group) group.push(event);
    else bySubject.set(key, [event]);
  }

  const batches: TelemetryBatch[] = [];
  // Array.from rather than iterating the map view directly: this package
  // targets ES2021 without downlevelIteration.
  for (const group of Array.from(bySubject.values())) {
    const first = group[0]!;
    for (const part of chunk(group, MAX_TELEMETRY_BATCH)) {
      batches.push({
        // Exactly one of the two, matching what the endpoint requires.
        ...(first.userId != null
          ? { userId: first.userId }
          : { anonSessionId: first.anonSessionId }),
        events: part.map((event) => ({ type: event.type, payload: event.payload })),
      });
    }
  }
  return batches;
}

export function createTelemetryQueue(options: TelemetryQueueOptions): TelemetryQueue {
  const maxQueued = options.maxQueued ?? DEFAULT_MAX_QUEUED;
  let queued: QueuedTelemetryEvent[] = [];
  let userId: string | null = null;
  // Serializes flushes so two overlapping ones cannot send the same event
  // twice — an interval tick landing on top of a background flush is the
  // ordinary case, not an edge one.
  let inFlight: Promise<void> = Promise.resolve();

  return {
    track(type, payload) {
      queued.push({ type, payload, userId, anonSessionId: options.anonSessionId });
      // Drop from the FRONT: during an outage the newest events are the ones
      // still worth having, and the oldest have already lost their context.
      if (queued.length > maxQueued) queued = queued.slice(queued.length - maxQueued);
    },

    flush() {
      inFlight = inFlight.then(async () => {
        if (queued.length === 0) return;
        // Taken before the first await: anything tracked during the send
        // belongs to the next flush, not this one.
        const sending = queued;
        queued = [];
        try {
          for (const batch of groupBySubject(sending)) {
            try {
              await options.send(batch);
            } catch {
              // Dropped, deliberately, and never surfaced. Re-queueing a batch
              // the API cannot accept turns one unreachable API into an
              // ever-growing retry loop on a phone; losing analytics is the
              // cheaper failure by a wide margin (docs/adr/0038).
            }
          }
        } catch {
          // Anything the loop itself throws is swallowed for the same reason,
          // and for one more: this promise is the chain every LATER flush is
          // queued behind, so letting it reject would turn a single failure
          // into every subsequent flush rejecting too.
        }
      });
      return inFlight;
    },

    setUser(next) {
      userId = next;
    },

    size() {
      return queued.length;
    },
  };
}

/**
 * Guards against emitting the same screen view twice in a row.
 *
 * Both clients emit from an effect keyed on the current route, and an effect
 * can run more than once for one navigation: React StrictMode deliberately
 * double-invokes them in development, and a re-render can too. Without this,
 * dev traffic double-counts every screen and the funnel's absolute numbers are
 * quietly wrong — the kind of bug that is invisible until someone reads them.
 *
 * Consecutive only: A -> B -> A is three views, because returning to a screen
 * genuinely is one. Shared rather than written twice, since a funnel that
 * counted web and mobile differently would compare nothing (CLAUDE.md §3).
 */
export function createScreenViewGate(): (screen: TelemetryScreen) => boolean {
  let last: TelemetryScreen | null = null;
  return (screen) => {
    if (screen === last) return false;
    last = screen;
    return true;
  };
}
